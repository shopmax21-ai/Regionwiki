export type Job = {
  slug: string;
  title: string;
  kind: JobKind;
  /** Уровень персонажа, с которого работа доступна. 0 — доступна сразу. */
  level: number;
  /** Альтернативный путь: 2 ранг на одной из работ предыдущего этапа (slug). */
  altRanks?: string[];
  /** Короткое описание для карточки */
  tagline: string;
  /** Вводный абзац статьи */
  intro: string;
  /** Что нужно для старта: транспорт, инструменты, лицензии */
  conditions: string[];
  /** Как формируется доход */
  income: string[];
  /** Пошаговый процесс */
  process: string[];
  /** Советы новичкам */
  tips: string[];
  /** Особенности совместной работы (если есть) */
  teamwork?: string;
  /** Подсказка по навигатору */
  navigator?: string;
  /** Картинка 16:9: путь вида /images/... или ссылка https://. Если не задана, берётся из job-images.ts или заглушка. */
  image?: string;
  /** Дополнительные разделы гайда, которые редакторы добавляют сами (старый формат, см. blocks) */
  sections?: GuideSection[];
  /**
   * Содержимое гайда из блочного редактора. Если поле задано, оно полностью заменяет conditions, income, process,
   * tips, teamwork, navigator и sections. У встроенных работ его нет: они переводятся в блоки на лету (jobBlocks).
   */
  blocks?: GuideBlock[];
};

/** Свободный раздел гайда: заголовок и список пунктов. */
export type GuideSection = { title: string; items: string[] };

export type CalloutVariant = "tip" | "info" | "warning";

export const calloutVariants: Record<CalloutVariant, string> = {
  tip: "Совет",
  info: "Заметка",
  warning: "Важно",
};

/** Блок гайда: из них редактор собирает страницу работы. Заголовки блоков попадают в содержание страницы. */
export type GuideBlock =
  | { type: "heading"; text: string }
  | { type: "text"; text: string }
  | { type: "list"; ordered: boolean; items: string[] }
  | { type: "callout"; variant: CalloutVariant; text: string }
  | { type: "image"; src: string; caption?: string }
  | { type: "slider"; slides: { src: string; caption?: string }[] }
  /** Текст с картинкой сбоку: для объяснений «как пользоваться телефоном, меню, интерфейсом». Без картинки показывается как обычный текст. */
  | { type: "textImage"; side: "left" | "right"; text: string; src?: string; caption?: string }
  /** Интерактивная карта с указанными местами: для «где находится работа, магазин, точка сдачи». */
  | { type: "map"; title?: string; places: GuideMapPlace[] };

export type GuideBlockType = GuideBlock["type"];

/** Место на карте внутри гайда. Хранится вместе с гайдом, поэтому правка меток на общей карте его не ломает. */
export type GuideMapPlace = {
  name: string;
  /** Игровые координаты, как на общей карте */
  x: number;
  y: number;
  /** Категория определяет цвет метки (id из карты: job, shop, state, transport, leisure, other) */
  category: string;
  /** Своя иконка: id готовой иконки или адрес картинки. Без неё берётся иконка категории. */
  icon?: string;
  description?: string;
};

