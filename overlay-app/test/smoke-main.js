const { app, BrowserWindow } = require("electron");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ovl-"));
app.setPath("userData", tmp);
fs.writeFileSync(path.join(tmp, "settings.json"), JSON.stringify({ serverUrl: "http://127.0.0.1:4599", token: "secret" }));
fs.writeFileSync(path.join(tmp, "binds.json"), JSON.stringify([{ id: "b1", title: "Приветствие", hotkey: "Ctrl+Alt+1", text: "Здравствуйте!\nПриступаю к репорту", openKey: "", delay: "" }]));
require("../main.js");
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
process.on("unhandledRejection", (e) => { console.log("UNHANDLED", e); process.exit(1); });
app.whenReady().then(async () => {
  await wait(2500);
  const win = BrowserWindow.getAllWindows().find((w) => w.webContents.getURL().endsWith("index.html"));
  const js = (code) => win.webContents.executeJavaScript(code);
  await js(`document.getElementById('all-q').value='прив'; document.getElementById('all-q').dispatchEvent(new Event('input'))`);
  await wait(300);
  const allKinds = await js(`[...document.querySelectorAll('#all-list .badge, #all-list .sect')].map(e=>e.textContent)`);
  await js(`document.getElementById('all-q').value='ограбление'; document.getElementById('all-q').dispatchEvent(new Event('input'))`);
  await wait(300);
  fs.writeFileSync("/tmp/shot-all.png", (await win.webContents.capturePage()).toPNG());
  const huds = BrowserWindow.getAllWindows().filter((w) => w !== win);
  let hudInfo = null;
  if (huds[0]) { hudInfo = { visible: huds[0].isVisible(), bounds: huds[0].getBounds(), rows: await huds[0].webContents.executeJavaScript("document.querySelectorAll('.row').length") }; fs.writeFileSync("/tmp/shot-hud.png", (await huds[0].webContents.capturePage()).toPNG()); }
  await js(`document.querySelector('[data-tab=rules]').click()`);
  await js(`document.getElementById('rules-q').value='ОП 1.19'; document.getElementById('rules-q').dispatchEvent(new Event('input'))`);
  await wait(300);
  const n1 = await js(`document.querySelectorAll('#rules-list .card').length`);
  await js(`document.getElementById('rules-q').value='ограбить'; document.getElementById('rules-q').dispatchEvent(new Event('input')); document.querySelector('#rules-list .more').click()`);
  await wait(300);
  fs.writeFileSync("/tmp/shot-rules.png", (await win.webContents.capturePage()).toPNG());
  await js(`document.querySelector('[data-tab=replies]').click()`);
  await wait(200);
  const replies = await js(`[...document.querySelectorAll('#replies-list .reply-title')].map(e=>e.textContent)`);
  fs.writeFileSync("/tmp/shot-replies.png", (await win.webContents.capturePage()).toPNG());
  await js(`document.querySelector('[data-tab=binder]').click()`);
  await wait(200);
  const binds = await js(`document.querySelectorAll('#binder-list .bind').length`);
  fs.writeFileSync("/tmp/shot-binder.png", (await win.webContents.capturePage()).toPNG());
  console.log("RESULT", JSON.stringify({ allKinds, hudInfo, refQueryHits: n1, replies, binds }));
  process.exit(0);
});
